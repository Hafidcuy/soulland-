package com.soulland.soul;

/** Bentuk visual yang dipakai untuk menggambar efek skill. */
public enum FxShape {
    /** Bola partikel mengembang dari titik asal. */
    SPHERE,
    /** Garis lurus dari pemain ke arah pandang. */
    LINE,
    /** Kerucut di depan pemain. */
    CONE,
    /** Cincin datar menempel di tanah. */
    RING,
    /** Cakram datar di tanah. */
    PLANE,
    /** Pilar vertikal dari tanah ke atas. */
    COLUMN,
    /** Semburan ke segala arah lalu jatuh. */
    BURST
}
